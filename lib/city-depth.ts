/**
 * city-depth.ts — the per-city depth layer for the 23 location pages.
 *
 * THE PROBLEM THIS SOLVES. Measured on the export before this file existed: every city page was
 * 123–129 words at 19–26% unique 5-grams. The only thing that changed between them was the city
 * name. That is the textbook doorway set described in docs/content-standards.md §4, and the reason
 * it matters more than a thin page normally would is that the penalty lands on the DOMAIN, not on
 * the 23 pages — it would take the 8 service pages and the homepage down with it.
 *
 * WHAT LEGITIMATELY DIFFERENTIATES A CITY PAGE. Not tone, not synonyms for "professional", and not
 * a claim about work we did there. The honest axis is physical: WHICH ROOFS EXIST IN THIS CITY.
 * Building era, construction type and distance from the sea decide what fails and how it is sealed.
 * A 1930s International-Style flat roof in Tel Aviv, a 1950s shikun block in Bat Yam, a tiled
 * private roof in Ramat HaSharon and a 2015 tower in Rosh HaAyin fail in four different ways, and
 * the correct service differs for each. That is real, publicly checkable, and specific.
 *
 * WHAT IS NOT IN HERE, DELIBERATELY:
 *   - No claim that we have worked in a given city, or how many roofs, or for whom.
 *   - No customer names, no city-specific response time, no city-specific price.
 *   - No invented neighbourhood names. Where a district is named it is one that unambiguously
 *     exists; where confidence was lower the copy describes the building stock instead. An invented
 *     street name is a fabrication about the world even though it is not a business fact.
 * Anything an owner would have to confirm belongs in docs/business-facts.md, not on a page.
 *
 * Statements about building stock are hedged on purpose — "רוב", "חלק ניכר", "נפוץ". Cities are not
 * uniform, and an absolute claim about one would be false somewhere inside it.
 *
 * See lib/service-depth.ts for the sibling file and the same reasoning applied to services.
 */
